const buildStressLists = (dataset: StressDatasetMode): StressListConfig[] => {
  const singleList: StressListConfig[] = [
    {
      title: 'Stress: Single massive list (300 tasks)',
      taskCount: 300,
    },
  ];

  const tenHeavyLists: StressListConfig[] = Array.from(
    { length: 10 },
    (_, index) => ({
      title: `Stress: Team queue #${index + 1}`,
      taskCount: 80,
    }),
  );

  const manyLists: StressListConfig[] = Array.from(
    { length: 30 },
    (_, index) => ({
      title: `Stress: Compact board #${index + 1}`,
      taskCount: 30,
    }),
  );

  switch (dataset) {
    case 'single':
      return singleList;
    case 'ten':
      return tenHeavyLists;
    case 'many':
      return manyLists;
    case 'all':
    default:
      return [...singleList, ...tenHeavyLists, ...manyLists];
  }
};

const clearUserData = async (userId: number) => {
  await prisma.task.deleteMany({
    where: {
      todolist: {
        userId,
      },
    },
  });

  await prisma.todolist.deleteMany({
    where: { userId },
  });
};

const createTasksInChunks = async (data: Prisma.TaskCreateManyInput[]) => {
  for (let index = 0; index < data.length; index += TASK_INSERT_CHUNK_SIZE) {
    await prisma.task.createMany({
      data: data.slice(index, index + TASK_INSERT_CHUNK_SIZE),
    });
  }
};

const seedBasicLists = async (userId: number) => {
  let totalTasks = 0;

  for (let listIndex = 0; listIndex < basicLists.length; listIndex += 1) {
    const listConfig = basicLists[listIndex];
    const createdList = await prisma.todolist.create({
      data: {
        title: listConfig.title,
        order: listIndex,
        userId,
      },
    });

    await prisma.task.createMany({
      data: listConfig.tasks.map((task, taskIndex) => ({
        title: task.title,
        description: task.description,
        status: task.status,
        priority: task.priority,
        order: taskIndex,
        startDate: task.startDate ?? null,
        deadline: task.deadline ?? null,
        todoListId: createdList.id,
      })),
    });

    totalTasks += listConfig.tasks.length;
  }

  return {
    totalLists: basicLists.length,
    totalTasks,
  };
};

const seedStressLists = async (userId: number, dataset: StressDatasetMode) => {
  const lists = buildStressLists(dataset);

  let totalTasks = 0;
  for (let listIndex = 0; listIndex < lists.length; listIndex += 1) {
    const listConfig = lists[listIndex];
    const createdList = await prisma.todolist.create({
      data: {
        userId,
        title: listConfig.title,
        order: listIndex,
      },
    });

    const tasks: Prisma.TaskCreateManyInput[] = Array.from(
      { length: listConfig.taskCount },
      (_, taskIndex) => ({
        title: buildTaskTitle(taskIndex),
        description: buildTaskDescription(taskIndex),
        status: taskIndex % 4,
        priority: taskIndex % 5,
        order: taskIndex,
        startDate: null,
        deadline: null,
        todoListId: createdList.id,
      }),
    );

    await createTasksInChunks(tasks);
    totalTasks += listConfig.taskCount;
  }

  return {
    totalLists: lists.length,
    totalTasks,
  };
};

async function main() {
  const passwordHash = await bcrypt.hash(DEMO_PASSWORD, 10);

  const user = await prisma.user.upsert({
    where: { email: DEMO_EMAIL },
    create: {
      email: DEMO_EMAIL,
      login: 'admin',
      passwordHash,
    },
    update: {
      login: 'admin',
      passwordHash,
    },
  });

  await clearUserData(user.id);

  if (seedMode === 'stress') {
    const result = await seedStressLists(user.id, stressDatasetMode);
    console.log(
      `Stress seed complete: dataset=${stressDatasetMode}, lists=${result.totalLists}, tasks=${result.totalTasks}`,
    );
  } else {
    const result = await seedBasicLists(user.id);
    console.log(
      `Basic seed complete: lists=${result.totalLists}, tasks=${result.totalTasks}`,
    );
  }

  console.log(`Demo credentials: ${DEMO_EMAIL} / ${DEMO_PASSWORD}`);
}

main()
  .catch(error => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
