import bcrypt from 'bcryptjs';
import { PrismaClient, type Prisma } from '@prisma/client';

const prisma = new PrismaClient();

const DEMO_EMAIL = 'admin';
const DEMO_PASSWORD = 'admin';
const TASK_INSERT_CHUNK_SIZE = 60;

type SeedMode = 'basic' | 'stress';
type StressDatasetMode = 'single' | 'ten' | 'many' | 'all';

type StressListConfig = {
  title: string;
  taskCount: number;
};

type DemoTaskConfig = {
  title: string;
  description: string | null;
  status: number;
  priority: number;
  startDate?: Date | null;
  deadline?: Date | null;
};

type DemoListConfig = {
  title: string;
  tasks: DemoTaskConfig[];
};

const seedMode: SeedMode =
  process.env.SEED_MODE === 'stress' ? 'stress' : 'basic';

const stressDatasetMode: StressDatasetMode = (() => {
  switch (process.env.STRESS_DATASET) {
    case 'single':
    case 'ten':
    case 'many':
      return process.env.STRESS_DATASET;
    default:
      return 'all';
  }
})();

const buildTaskTitle = (taskIndex: number): string => {
  const id = taskIndex + 1;
  if (taskIndex % 3 === 0) {
    return `Task ${id}: quick follow-up`;
  }
  if (taskIndex % 3 === 1) {
    return `Task ${id}: verify details for release checklist and prepare next action`;
  }
  return `Task ${id}: coordinate cross-team updates, document progress, and confirm acceptance criteria before moving the card to completed state`;
};

const buildTaskDescription = (taskIndex: number): string | null => {
  if (taskIndex % 5 !== 0) return null;
  return `Autogenerated stress item #${taskIndex + 1} for responsive and layout checks.`;
};

const createRelativeDate = (daysOffset: number, hour: number): Date => {
  const date = new Date();

  date.setDate(date.getDate() + daysOffset);
  date.setHours(hour, 0, 0, 0);

  return date;
};

